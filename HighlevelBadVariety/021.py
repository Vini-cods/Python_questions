#Escreva um programa que peça ao usuário um número de 1 a 7 e imprima o dia da semana correspondente (1 é segunda-feira, 2 é terça-feira, etc.).

numero = int(input('Digite um número de 1 a 7: '))
if numero == 1:
    print('Segunda-feira')
if numero == 2:
    print('Terça-feira')
if numero == 3:
    print('Quarta-feira')
if numero == 4:
    print('Quinta-feira')
if numero == 5:
    print('Sexta-feira')
if numero == 6:
    print('Sábado')
if numero == 7:
    print('Domingo')